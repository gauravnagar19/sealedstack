#!/usr/bin/env python3
"""Interactive wizard that scaffolds an infra repo (spec section 10, v1.0).

Reference: docs/maintainers/spec.md section
6. Writes ``config/`` (stack.yaml, servers.yaml, apps.yaml) and, unless the
config dir is inside this checkout, the surrounding infra repo
(``sealedstack.version``, ``bin/sealedstack``, ``.github/workflows/sealedstack.yml``,
``.gitignore``, ``README.md``). Refuses to overwrite unless --force.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import pathlib
import stat
import sys
import urllib.error
import urllib.request

import yaml

import configdir

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "engine"))
from sealedstack import scaffold  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
# The engine image owner is the repository owner (or --owner / SEALEDSTACK_IMAGE_OWNER);
# there is no placeholder default.
TAILSCALE_POLICY_URL = "https://api.tailscale.com/api/v2/tailnet/-/acl"
TAILSCALE_TOKEN_URL = "https://api.tailscale.com/api/v2/oauth/token"

POLICY_HEADER = """// Tailnet policy imported by `sealedstack setup` from the Tailscale API (D-026).
// sealedstack merges only its own tags, rules and tests into this file at plan
// time; every rule below is preserved. Edit freely.
"""


def fetch_tailscale_policy() -> str:
    """Import the current tailnet policy as HuJSON (spec section 7, D-026).

    Uses the OAuth client (client-credentials flow), never a long-lived API key
    (Task 4.2).
    """
    client_id = os.environ.get("TAILSCALE_OAUTH_CLIENT_ID", "").strip()
    client_secret = os.environ.get("TAILSCALE_OAUTH_CLIENT_SECRET", "").strip()
    if not (client_id and client_secret):
        raise RuntimeError(
            "TAILSCALE_OAUTH_CLIENT_ID/_SECRET are not set (needed to import your tailnet policy)"
        )
    basic = base64.b64encode(f"{client_id}:{client_secret}".encode("utf-8")).decode("ascii")
    token_request = urllib.request.Request(
        TAILSCALE_TOKEN_URL,
        data=b"grant_type=client_credentials",
        headers={
            "Authorization": f"Basic {basic}",
            "Content-Type": "application/x-www-form-urlencoded",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(token_request, timeout=30) as response:
            token = json.loads(response.read().decode("utf-8"))["access_token"]
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace").strip()
        raise RuntimeError(f"Tailscale OAuth token exchange returned HTTP {exc.code}: {detail}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"could not reach the Tailscale API: {exc.reason}") from exc

    request = urllib.request.Request(
        TAILSCALE_POLICY_URL,
        headers={"Authorization": f"Bearer {token}", "Accept": "application/hujson"},
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read().decode("utf-8")
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace").strip()
        raise RuntimeError(f"Tailscale API returned HTTP {exc.code}: {detail}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"could not reach the Tailscale API: {exc.reason}") from exc


def git_owner() -> str:
    """The owner of the origin remote of the current directory, or ""."""
    import re
    import subprocess

    try:
        url = subprocess.run(["git", "remote", "get-url", "origin"], capture_output=True, text=True, timeout=10).stdout.strip()
    except Exception:  # noqa: BLE001
        return ""
    match = re.search(r"github\.com[:/]([^/]+)/", url)
    return match.group(1) if match else ""


def ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    answer = input(f"{prompt}{suffix}: ").strip()
    return answer or default


def read_version() -> str:
    return (ROOT / "VERSION").read_text(encoding="utf-8").strip()


def write_file(path: pathlib.Path, content: str, *, force: bool, executable: bool = False) -> bool:
    """Write ``content`` unless the file exists and ``force`` is false."""
    if path.exists() and not force:
        print(f"  keep  {path}")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    if executable:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"  write {path}")
    return True


def wrapper_script(image: str) -> str:
    template = """#!/usr/bin/env bash
# Generated by `sealedstack setup`. Runs the pinned sealedstack image against
# this repo. The host needs only Docker.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
version="$(cat "$here/sealedstack.version")"

tty_args=()
[ -t 0 ] && tty_args=(-t)

# Mount the ssh-agent. On macOS Docker Desktop forwards the launchd agent at
# the well-known host-services socket; elsewhere bind the host socket (quoted,
# it may contain spaces).
ssh_args=()
if [ "$(uname -s)" = "Darwin" ]; then
  ssh_args=(-v /run/host-services/ssh-auth.sock:/ssh-agent -e SSH_AUTH_SOCK=/ssh-agent)
elif [ -n "${SSH_AUTH_SOCK:-}" ]; then
  ssh_args=(-v "${SSH_AUTH_SOCK}:/ssh-agent" -e SSH_AUTH_SOCK=/ssh-agent)
fi

# Pass through the environment the commands read. `docker run -e VAR` forwards
# the value only when it is set in the invoking shell, so unset vars are fine.
env_args=(
  -e BWS_ACCESS_TOKEN
  -e GH_TOKEN
  -e TAILSCALE_OAUTH_CLIENT_ID
  -e TAILSCALE_OAUTH_CLIENT_SECRET
  -e ROOT_PASSWORD
  -e CLOUDFLARE_API_TOKEN
  -e CLOUDFLARE_ACCOUNT_ID
)

# The ${arr[@]+...} guards keep `set -u` happy on empty arrays (bash 3.2, the
# stock macOS shell). --init reaps child processes.
exec docker run --rm --init -i ${tty_args[@]+"${tty_args[@]}"} ${ssh_args[@]+"${ssh_args[@]}"} ${env_args[@]+"${env_args[@]}"} \\
  -v "$here:/infra" -w /infra \\
  -e SEALEDSTACK_CONFIG=/infra/config \\
  -e SEALEDSTACK_WORKDIR=/infra/.sealedstack \\
  "__IMAGE__:${version}" "$@"
"""
    return template.replace("__IMAGE__", image)


def infra_workflow(owner: str, version: str) -> str:
    """The infra repo's CI stub (journey A step 2): calls the reusable workflow."""
    template = """name: sealedstack

on:
  workflow_dispatch:
    inputs:
      command:
        type: choice
        options: [setup, check, plan, apply, up, add-server, add-app, reinstall, status, backup, restore, drill, drift, verify]
      args:
        description: "e.g. --name server-1 (IP and root password come from the secret source)"
        required: false
  pull_request:
  push:
    branches: [main]
  issue_comment:
    types: [created]
  schedule:
    - cron: "17 * * * *"          # hourly status (+ drift if SEALEDSTACK_DRIFT_ENABLED=true)
    - cron: "0 3 * * 0"           # weekly restore drill (Sunday 03:00 UTC)
jobs:
  sealedstack:
    uses: __OWNER__/sealedstack/.github/workflows/infra.yml@v__VERSION__
    with:
      command: ${{ inputs.command }}
      args: ${{ inputs.args }}
    secrets: inherit
    permissions: { contents: write, pull-requests: write, issues: write, id-token: write, packages: read }
"""
    return template.replace("__OWNER__", owner).replace("__VERSION__", version)


def infra_readme(infra_name: str, image: str) -> str:
    return f"""# {infra_name}

Configuration for a sealedstack sealed origin. This repo holds only config and a
pinned tool version — no secrets and no sealedstack source code.

## Run it

The host needs **Docker only**. `bin/sealedstack` runs the pinned image against
this repo:

```sh
bin/sealedstack plan      # render + plan, no changes
bin/sealedstack apply     # apply the edge and platform stacks
bin/sealedstack doctor    # check tokens, permissions and the zone
```

The tool version is pinned in `sealedstack.version`; upgrading means editing
that one line. The image is `{image}`.

Secrets (from your secrets manager) are passed as environment variables, e.g.
`BWS_ACCESS_TOKEN` and `GH_TOKEN`. Generated files and build output live under
`.sealedstack/` (gitignored).

See `config/` for the stack, servers and apps, and the sealedstack docs for the
command reference.
"""


def scaffold_infra(
    infra_root: pathlib.Path,
    *,
    infra_name: str,
    image: str,
    version: str,
    owner: str,
    force: bool,
) -> None:
    print(f"\nscaffolding infra repo at {infra_root}:")
    write_file(infra_root / "sealedstack.version", f"{version}\n", force=force)
    write_file(
        infra_root / "bin" / "sealedstack",
        wrapper_script(image),
        force=force,
        executable=True,
    )
    write_file(
        infra_root / ".github" / "workflows" / "sealedstack.yml",
        infra_workflow(owner, version),
        force=force,
    )
    write_file(
        infra_root / ".devcontainer" / "devcontainer.json",
        scaffold.devcontainer_json(f"{image}:{version}"),
        force=force,
    )
    write_file(infra_root / ".gitignore", scaffold.gitignore(), force=force)
    write_file(infra_root / "README.md", infra_readme(infra_name, image), force=force)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    parser.add_argument(
        "--infra-name",
        default=None,
        help="infra repo name, e.g. my-infra (D-028); asked interactively if omitted",
    )
    parser.add_argument(
        "--owner",
        default=os.environ.get("SEALEDSTACK_IMAGE_OWNER") or git_owner(),
        help="owner (GitHub org/user) of the engine image and the approver "
        "(default: the owner of this repository's origin remote)",
    )
    parser.add_argument(
        "--image",
        default=None,
        help="full sealedstack tool image for the generated wrapper "
        f"(default: ghcr.io/<owner>/sealedstack)",
    )
    parser.add_argument(
        "--no-scaffold",
        action="store_true",
        help="write config/ only; do not create the surrounding infra repo",
    )
    parser.add_argument(
        "--config-dir",
        default=None,
        help="write config here (default: $SEALEDSTACK_CONFIG, else <repo>/config)",
    )
    args = parser.parse_args()

    if not args.owner and not args.image:
        print("could not tell the owner of the engine image: pass --owner <github-user-or-org> "
              "(or run inside the infra repo, whose origin remote names it)", file=sys.stderr)
        return 1
    # --image wins; otherwise derive the published image from the owner.
    image = args.image or f"ghcr.io/{args.owner}/sealedstack"

    config = pathlib.Path(args.config_dir).expanduser() if args.config_dir else configdir.config_dir()
    infra_root = config.parent

    existing = [p for p in ("stack.yaml", "servers.yaml", "apps.yaml") if (config / p).exists()]
    if existing and not args.force:
        print(f"{config}/ already has {', '.join(existing)}; re-run with --force to overwrite.", file=sys.stderr)
        return 1

    infra_name = args.infra_name or ask("Infra repo name", "sealedstack-infra")
    domain = ask("Apex domain", "example.com")
    owner_email = ask("Owner email (Access policy)")
    admin_user = ask("Linux admin user", "admin")
    admin_ssh_key = ask("Your SSH public key (blank to add later in config/stack.yaml)")
    account_id = ask("Cloudflare account id (dashboard)")
    team_name = ask("Cloudflare Zero Trust team name", domain.split(".")[0])
    tailnet = ask("Tailscale MagicDNS suffix (tailnet, e.g. tail1234.ts.net)")

    server_rows: list = []
    print("Servers (blank name to finish). Providers: any-ssh netcup hetzner hostinger digitalocean vultr")
    while True:
        name = ask("  server name", "server-1" if not server_rows else "")
        if not name:
            break
        provider = ask(f"  provider for {name}", "any-ssh")
        role = ask(f"  role for {name} (control|worker)", "control" if not server_rows else "worker")
        os_name = ask(f"  os for {name}", "ubuntu-24.04")
        server_rows.append((name, provider, role, os_name))

    servers = scaffold.servers_config(server_rows)["servers"]
    if not any(s["role"] == "control" for s in servers.values()):
        print("at least one server must have role: control", file=sys.stderr)
        return 1

    stack = scaffold.stack_config(
        infra_name=infra_name,
        domain=domain,
        owner_email=owner_email,
        admin_user=admin_user,
        ssh_keys=[admin_ssh_key] if admin_ssh_key else [],
        approvers=[args.owner] if args.owner else [],
        account_id=account_id,
        team_name=team_name,
        tailnet=tailnet,
    )
    apps = scaffold.apps_config(next(iter(servers)), domain)

    # Import the current tailnet policy verbatim before writing anything, so a
    # failed import leaves no half-written config (spec section 7, D-026).
    try:
        policy_text = fetch_tailscale_policy()
    except RuntimeError as exc:
        print(f"init: could not import the Tailscale policy: {exc}", file=sys.stderr)
        return 1

    config.mkdir(parents=True, exist_ok=True)
    (config / "stack.yaml").write_text(yaml.safe_dump(stack, sort_keys=False), encoding="utf-8")
    (config / "servers.yaml").write_text(yaml.safe_dump({"servers": servers}, sort_keys=False), encoding="utf-8")
    (config / "apps.yaml").write_text(yaml.safe_dump(apps, sort_keys=False), encoding="utf-8")
    policy_body = policy_text if policy_text.endswith("\n") else policy_text + "\n"
    (config / "tailscale-policy.hujson").write_text(POLICY_HEADER + policy_body, encoding="utf-8")

    print(f"\nwrote {config}/stack.yaml, servers.yaml, apps.yaml")
    print(f"imported your Tailscale policy -> {config}/tailscale-policy.hujson")

    # Scaffold the surrounding infra repo, unless config lives inside the
    # sealedstack checkout itself (the contributor flow) or the user opts out.
    inside_repo = infra_root == ROOT or ROOT in infra_root.parents
    if args.no_scaffold:
        print("skipping infra-repo scaffold (--no-scaffold)")
    elif inside_repo:
        print(f"config is inside the sealedstack checkout ({ROOT}); not scaffolding an infra repo here")
    else:
        scaffold_infra(
            infra_root,
            infra_name=infra_name,
            image=image,
            version=read_version(),
            owner=args.owner,
            force=args.force,
        )

    print("\nnext: run `bin/sealedstack check`")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
