"""Create the Dokploy admin account and an API key on first boot (G2, D-044).

Pinned to Dokploy v0.30.8 (``ansible/roles/platform_dokploy/defaults/main.yml``);
the endpoints below were read from that tag's source (``packages/server/src/lib/auth.ts``,
``apps/dokploy/server/api/routers/user.ts``, ``openapi.json``):

1. ``POST /api/auth/sign-up/email`` {email, password, name, lastName}. On a fresh
   panel the first account becomes the owner of a new organisation and is signed in
   (``Set-Cookie`` session). Once an owner exists it answers 400 "Admin is already
   created".
2. ``POST /api/auth/sign-in/email`` {email, password} for a panel whose admin we
   created in an earlier, interrupted run.
3. ``GET /api/user.session`` (cookie) -> ``session.activeOrganizationId``.
4. ``POST /api/user.createApiKey`` (cookie) {name, metadata: {organizationId}, rateLimitEnabled: false} -> the
   key (``key``), shown by Dokploy only once, so it is stored immediately.
5. ``GET /api/project.all`` with ``x-api-key`` proves the key works.

The admin password is generated by the ``generated`` stack, unless the operator keeps one in the
secret source (``DOKPLOY_ADMIN_PASSWORD``, D-076), which then wins and is applied to the panel. The API key is
stored back into the state: both live only in the encrypted state (D-038). Re-running is
safe: a stored, working key is reused and nothing is created. A key placed in the
secret source (``DOKPLOY_API_KEY``) wins and skips all of this.
"""
from __future__ import annotations

import sys
import time
from typing import Callable, Optional

from . import config as config_mod
from . import dokploy as dokploy_mod
from . import generated as generated_mod
from . import secrets as secrets_mod
from .http import HttpClient, Response, UrllibClient

KEY_NAME = "sealedstack"
MIN_PASSWORD = 12  # an admin password kept in the secret source (D-076)


class BootstrapError(config_mod.ConfigError):
    pass


def _cookie_header(response: Response) -> str:
    pairs = []
    for cookie in response.set_cookies:
        pair = cookie.split(";", 1)[0].strip()
        if "=" in pair and not pair.endswith("="):
            pairs.append(pair)
    return "; ".join(pairs)


def _data(response: Response):
    """The payload of a REST response (also tolerates the tRPC ``result.data.json`` envelope)."""
    try:
        body = response.json()
    except Exception:  # noqa: BLE001
        return None
    if isinstance(body, dict) and isinstance(body.get("result"), dict):
        inner = body["result"].get("data")
        if isinstance(inner, dict) and "json" in inner:
            return inner["json"]
        return inner
    return body


class Bootstrapper:
    def __init__(
        self,
        base_url: str,
        email: str,
        *,
        http: Optional[HttpClient] = None,
        sleep: Callable[[float], None] = time.sleep,
        out=None,
    ) -> None:
        self.base = base_url.rstrip("/")
        self.email = email
        self.http = http or UrllibClient()
        self.sleep = sleep
        self.out = out if out is not None else sys.stderr

    def _headers(self, cookie: str = "") -> dict:
        headers = {"Accept": "application/json", "Origin": self.base, "Content-Type": "application/json"}
        if cookie:
            headers["Cookie"] = cookie
        return headers

    def wait_ready(self, attempts: int = 60, delay: float = 5.0) -> None:
        for _ in range(attempts):
            try:
                if self.http.request("GET", f"{self.base}/api/settings.health", headers=self._headers()).status < 500:
                    return
            except Exception:  # noqa: BLE001 - not up yet
                pass
            self.sleep(delay)
        raise BootstrapError(
            f"the Dokploy panel at {self.base} did not answer. Check that the server joined the tailnet and that "
            "this runner is on it (tag:ci), then re-run `sealedstack up`."
        )

    def key_works(self, key: str) -> bool:
        if not key:
            return False
        try:
            response = self.http.request("GET", f"{self.base}/api/project.all", headers={"x-api-key": key, "Accept": "application/json"})
        except Exception:  # noqa: BLE001
            return False
        return response.status == 200

    def session(self, password: str) -> str:
        """A session cookie: sign up (fresh panel) or sign in (admin made by an earlier run)."""
        body = {"email": self.email, "password": password, "name": "sealedstack", "lastName": "admin"}
        response = self.http.request("POST", f"{self.base}/api/auth/sign-up/email", headers=self._headers(), json_body=body)
        cookie = _cookie_header(response)
        if response.status == 200 and cookie:
            print("dokploy: created the admin account", file=self.out)
            return cookie
        if response.status == 200 and not cookie:
            return self._sign_in(password)
        if "already created" in response.text.lower() or response.status in (400, 403, 422):
            return self._sign_in(password)
        raise BootstrapError(f"creating the Dokploy admin failed (HTTP {response.status}); see the Dokploy logs on the server")

    def _sign_in(self, password: str) -> str:
        response = self.http.request(
            "POST", f"{self.base}/api/auth/sign-in/email", headers=self._headers(),
            json_body={"email": self.email, "password": password},
        )
        cookie = _cookie_header(response)
        if response.status == 200 and cookie:
            print("dokploy: signed in as the admin created earlier", file=self.out)
            return cookie
        raise BootstrapError(
            "a Dokploy admin already exists that this setup did not create (or its password changed), so an API key "
            "cannot be created automatically. Create a key by hand (Settings, Profile, API/CLI Keys) and add it to the "
            "secret source as DOKPLOY_API_KEY; `up` then continues."
        )

    def _try_sign_in(self, password: str) -> str:
        """A session cookie for ``password``, or ``""`` when the panel does not accept it (never raises on a wrong password)."""
        response = self.http.request(
            "POST", f"{self.base}/api/auth/sign-in/email", headers=self._headers(),
            json_body={"email": self.email, "password": password},
        )
        cookie = _cookie_header(response)
        return cookie if response.status == 200 and cookie else ""

    def change_password(self, cookie: str, current: str, new: str) -> bool:
        response = self.http.request(
            "POST", f"{self.base}/api/auth/change-password", headers=self._headers(cookie),
            json_body={"currentPassword": current, "newPassword": new, "revokeOtherSessions": False},
        )
        return response.status == 200

    def sync_password(self, wanted: str, stored: str) -> str:
        """Make the admin's password ``wanted`` (the value the operator keeps in the secret source).

        ``unchanged``: it already is. ``changed``: the admin was signed in with the generated password ``stored`` and
        moved over. ``created``: a fresh panel got its admin with ``wanted``. Anything else is an error that says what to do."""
        if self._try_sign_in(wanted):
            return "unchanged"
        cookie = self._try_sign_in(stored) if stored else ""
        if cookie:
            if not self.change_password(cookie, stored, wanted):
                raise BootstrapError(
                    "Dokploy refused to change the admin password (change-password). Change it in the panel "
                    "(Profile) to the value in the secret source, then re-run `sealedstack up`."
                )
            if not self._try_sign_in(wanted):
                raise BootstrapError("the admin password was changed but the panel does not accept the new one; check the panel")
            return "changed"
        body = {"email": self.email, "password": wanted, "name": "sealedstack", "lastName": "admin"}
        response = self.http.request("POST", f"{self.base}/api/auth/sign-up/email", headers=self._headers(), json_body=body)
        if response.status == 200:
            return "created"
        raise BootstrapError(
            "a Dokploy admin exists whose password is neither the one in the secret source nor the one sealedstack generated, "
            "so it cannot be changed automatically. Set the secret-source value in the panel (Profile, password), or reset "
            "the panel's admin, then re-run `sealedstack up`."
        )

    def create_key(self, cookie: str) -> str:
        who = self.http.request("GET", f"{self.base}/api/user.session", headers=self._headers(cookie))
        org = ((_data(who) or {}).get("session") or {}).get("activeOrganizationId") if who.status == 200 else ""
        if not org:
            raise BootstrapError("could not read the Dokploy organisation of the admin (user.session)")
        created = self.http.request(
            "POST", f"{self.base}/api/user.createApiKey", headers=self._headers(cookie),
            # Without rateLimitEnabled=false Dokploy rejects the key with 401 after about five calls (measured on v0.30.8
            # in the first live `up`: the platform stack makes dozens), so every key is created with limiting off.
            json_body={"name": KEY_NAME, "metadata": {"organizationId": org}, "rateLimitEnabled": False},
        )
        data = _data(created) if created.status == 200 else None
        key = str((data or {}).get("key") or "") if isinstance(data, dict) else ""
        if not key:
            raise BootstrapError(f"creating the Dokploy API key failed (HTTP {created.status})")
        return key


def run(
    config: config_mod.Config,
    env,
    *,
    source: Optional[secrets_mod.SecretSource] = None,
    generated: Optional[generated_mod.Generated] = None,
    http: Optional[HttpClient] = None,
    sleep: Callable[[float], None] = time.sleep,
    out=None,
) -> str:
    """Make sure a working Dokploy API key exists. Returns where it came from:
    ``secret-source`` | ``state`` | ``created``."""
    out = out if out is not None else sys.stderr
    env = dict(env)
    source = source or secrets_mod.build_source(config.stack, config.config_dir, env)
    bootstrap = Bootstrapper(
        f"http://{dokploy_mod.control_host(config)}:3000",
        str(config.stack.get("owner_email") or ""),
        http=http, sleep=sleep, out=out,
    )

    override = secrets_mod.lookup(source, config, "DOKPLOY_API_KEY")
    if override.found:
        print("dokploy: using DOKPLOY_API_KEY from the secret source", file=out)
        return "secret-source"

    generated = generated or generated_mod.shared(config, env, source, http=http)
    state = generated.ensure()
    bootstrap.wait_ready()

    admin_password = str(state["dokploy_admin_password"])
    wanted = secrets_mod.lookup(source, config, "dokploy_admin_password")
    if wanted.found:
        if len(wanted.value) < MIN_PASSWORD:
            raise BootstrapError(
                f"{secrets_mod.describe(config, 'dokploy_admin_password')} must be at least {MIN_PASSWORD} characters"
            )
        outcome = bootstrap.sync_password(wanted.value, admin_password)
        print(f"dokploy: admin password from the secret source: {outcome}", file=out)
        admin_password = wanted.value

    stored = generated.api_key()
    if stored and bootstrap.key_works(stored):
        print("dokploy: the stored API key works; nothing to create", file=out)
        return "state"

    if not bootstrap.base or not bootstrap.email:
        raise BootstrapError("owner_email and a control server are needed to create the Dokploy admin")
    cookie = bootstrap.session(admin_password)
    key = bootstrap.create_key(cookie)
    generated.store(dokploy_api_key=key)  # before anything else can fail: Dokploy shows the key only once
    if not bootstrap.key_works(key):
        raise BootstrapError("the new Dokploy API key was rejected by the panel")
    print("dokploy: created an API key and stored it in the encrypted state", file=out)
    return "created"


def main(argv=None) -> int:
    import os

    env = dict(os.environ)
    config = config_mod.load_config(env=env)
    try:
        run(config, env)
    except config_mod.ConfigError as exc:
        print(f"sealedstack: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
